	CKINT(lc_sntrup_ss_ptr(&ptr, &len, &ws->ss1));
	rc += lc_compare(ptr, ss, len, "SNTRUP 953 enc SS");
	CKINT(lc_sntrup_dec(&ws->ss2, &ws->ct, &ws->sk));
	CKINT(lc_sntrup_ss_ptr(&ptr, &len, &ws->ss2));
	rc += lc_compare(ptr, ss, len, "SNTRUP 953 dec SS");

	/* loading of keys and encap / decap */
	CKINT(lc_sntrup_pk_load(&ws->pk, pk, sizeof(pk)));
	CKINT(lc_sntrup_sk_load(&ws->sk, sk, sizeof(sk)));
	CKINT(lc_sntrup_enc(&ws->ct, &ws->ss1, &ws->pk));
	CKINT(lc_sntrup_dec(&ws->ss2, &ws->ct, &ws->sk));
	CKINT(lc_sntrup_ss_ptr(&ptr, &len, &ws->ss1));
	CKINT(lc_sntrup_ss_ptr(&ptr2, &len2, &ws->ss2));
	rc += lc_compare(ptr, ptr2, len, "SNTRUP 953 dec SS");

